// composeKana replaces a kana followed by a combining sound mark with the
// precomposed kana ("か\u3099" with "が"). Fonts do not agree on where such
// a mark goes: VL Gothic draws U+3099 as a full-width character with the
// dots at its left, Noto Sans CJK as a zero-width mark left of its origin,
// and without shaping both land left of the kana. The precomposed kana is
// drawn as the font intends. Other text is returned as it is.
func composeKana(text string) string {
	if !strings.ContainsAny(text, "\u3099\u309a") {
		return text
	}
	var b strings.Builder
	prev := rune(-1)
	for _, r := range text {
		if c, ok := kanaPairs[[2]rune{prev, r}]; ok {
			prev = c
			continue
		}
		if prev >= 0 {
			b.WriteRune(prev)
		}
		prev = r
	}
	if prev >= 0 {
		b.WriteRune(prev)
	}
	return b.String()
}
