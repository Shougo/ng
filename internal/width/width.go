func in(r rune, t []span) bool {
	lo, hi := 0, len(t)-1
	for lo <= hi {
		m := (lo + hi) / 2
		switch {
		case r < t[m].lo:
			hi = m - 1
		case r > t[m].hi:
			lo = m + 1
		default:
			return true
		}
	}
	return false
}

// zero reports whether r takes no cell of its own: combining marks,
// zero-width joiners and variation selectors attach to the previous
// character.
func zero(r rune) bool {
	return unicode.In(r, unicode.Mn, unicode.Me) ||
		r == 0x200B || r == 0x200C || r == 0x200D ||
		(r >= 0xFE00 && r <= 0xFE0F) || (r >= 0xE0100 && r <= 0xE01EF) ||
		r == 0x3099 || r == 0x309A
}

// Rune returns the cells r takes: 0, 1 or 2. ambiDouble is true when
// 'ambiwidth' is "double".
func Rune(r rune, ambiDouble bool) int {
	switch {
	case r < 0x20 || (r >= 0x7F && r < 0xA0):
		return 0
	case r < 0xA1:
		return 1
	case zero(r):
		return 0
	case in(r, wide):
		return 2
	case ambiDouble && in(r, ambiguous):
		return 2
	}
	return 1
}

// Cell is one laid-out character: its text (a base character with any
// zero-width characters that follow it) and the cells it takes.
type Cell struct {
	Text  string
	Width int
}

// Layout splits s into cells. Zero-width characters join the character
// before them; a leading one stands alone in a single cell.
func Layout(s string, ambiDouble bool) []Cell {
	var out []Cell
	for i := 0; i < len(s); {
		r, n := utf8.DecodeRuneInString(s[i:])
		w := Rune(r, ambiDouble)
		if w == 0 && len(out) > 0 {
			out[len(out)-1].Text += s[i : i+n]
		} else {
			out = append(out, Cell{Text: s[i : i+n], Width: max(w, 1)})
		}
		i += n
	}
	return out
}

// Cells returns the total width of a layout.
func Cells(cells []Cell) int {
	n := 0
	for _, c := range cells {
		n += c.Width
	}
	return n
}
